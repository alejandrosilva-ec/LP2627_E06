package org.example.modelo;

/**
 * Define os perfis disponíveis para os utilizadores da aplicação.
 *
 * <p>{@link #USER} representa um utilizador comum e {@link #ADMIN} representa
 * um administrador. Estes valores permitem distinguir os papéis dos
 * utilizadores e apoiar a aplicação das permissões correspondentes.
 */
public enum Perfil {
    USER,
    ADMIN
}
